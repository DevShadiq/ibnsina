-- PostgreSQL / Neon-compatible employee portal schema and seed data.
-- Run this script while connected to the target Neon database. It replaces the
-- application tables below, matching the destructive behavior of the
-- original MySQL dump.

BEGIN;

SET LOCAL TIME ZONE 'UTC';

DROP TABLE IF EXISTS hr_empfamilydet, hr_empexamdet, hr_update_request, up_emp,
  hr_batch_control, admin_user CASCADE;

CREATE TABLE admin_user (
  user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(100) NOT NULL,
  password_hash varchar(255) NOT NULL,
  display_name varchar(200),
  user_type varchar(20) NOT NULL DEFAULT 'ADMIN',
  active_yn char(1) NOT NULL DEFAULT 'Y',
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_admin_username UNIQUE (username),
  CONSTRAINT ck_admin_user_type CHECK (user_type IN ('ADMIN', 'SUPER_ADMIN')),
  CONSTRAINT ck_admin_active_yn CHECK (active_yn IN ('Y', 'N'))
);

CREATE TABLE hr_batch_control (
  batch_no varchar(100) PRIMARY KEY,
  status varchar(10) NOT NULL DEFAULT 'INACTIVE',
  started_at timestamptz,
  closed_at timestamptz,
  created_by varchar(150),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_batch_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX ix_batch_status ON hr_batch_control (status);

