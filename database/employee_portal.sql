CREATE INDEX ix_up_emp_approval ON up_emp (approval_status);

CREATE TABLE hr_empexamdet (
  slno bigint NOT NULL,
  emp_entry_id bigint NOT NULL,
  empcode varchar(50),
  examname varchar(170),
  examgroup varchar(170),
  board varchar(1000),
  clas varchar(300),
  passyear varchar(100),
  remarks varchar(100),
  institute varchar(500),
  subject_name varchar(200),
  PRIMARY KEY (emp_entry_id, slno),
  CONSTRAINT fk_exam_emp_entry FOREIGN KEY (emp_entry_id)
    REFERENCES up_emp (emp_entry_id) ON DELETE CASCADE
);

CREATE INDEX ix_exam_entry ON hr_empexamdet (emp_entry_id);
CREATE INDEX ix_exam_empcode ON hr_empexamdet (empcode);

CREATE TABLE hr_empfamilydet (
  emp_entry_id bigint NOT NULL,
  empcode varchar(50),
  fname varchar(100),
  f_ocup varchar(70),
  f_add varchar(100),
  phone varchar(25),
  child_nos bigint NOT NULL,
  birth_date date,
  PRIMARY KEY (emp_entry_id, child_nos),
  CONSTRAINT fk_family_emp_entry FOREIGN KEY (emp_entry_id)
    REFERENCES up_emp (emp_entry_id) ON DELETE CASCADE
);

CREATE INDEX ix_family_entry ON hr_empfamilydet (emp_entry_id);
CREATE INDEX ix_family_empcode ON hr_empfamilydet (empcode);

CREATE TABLE hr_update_request (
  request_id uuid PRIMARY KEY,
  emp_entry_id bigint NOT NULL,
  ipi varchar(50),
  meritlist_id varchar(100) NOT NULL,
  class_id varchar(100) NOT NULL,
  batch_no varchar(100) NOT NULL,
  request_note varchar(1000),
  requested_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status varchar(10) NOT NULL DEFAULT 'PENDING',
  approved_at timestamptz,
  approved_until timestamptz,
  approved_by varchar(150),
  admin_remarks varchar(1000),
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_req_batch FOREIGN KEY (batch_no)
    REFERENCES hr_batch_control (batch_no),
  CONSTRAINT fk_req_emp_entry FOREIGN KEY (emp_entry_id)
    REFERENCES up_emp (emp_entry_id),
  CONSTRAINT ck_request_status CHECK (
    status IN ('PENDING', 'APPROVED', 'REJECTED', 'EXPIRED')
  )
);

CREATE INDEX ix_req_entry_status ON hr_update_request (emp_entry_id, status);
CREATE INDEX ix_req_approved_until ON hr_update_request (approved_until);
CREATE INDEX ix_req_batch ON hr_update_request (batch_no);

-- PostgreSQL does not support MySQL's ON UPDATE CURRENT_TIMESTAMP clause.
-- These triggers preserve that behavior for the two tables that used it.
CREATE OR REPLACE FUNCTION employee_portal_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$function$;

CREATE TRIGGER trg_batch_control_updated_at
BEFORE UPDATE ON hr_batch_control
FOR EACH ROW EXECUTE FUNCTION employee_portal_set_updated_at();

CREATE TRIGGER trg_update_request_updated_at
BEFORE UPDATE ON hr_update_request
FOR EACH ROW EXECUTE FUNCTION employee_portal_set_updated_at();

