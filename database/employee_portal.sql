  CONSTRAINT ck_emp_approval_status CHECK (
    approval_status IN ('DRAFT', 'PENDING', 'APPROVED', 'REJECTED')
  )
);

CREATE INDEX ix_up_emp_batch ON up_emp (batch_no);
